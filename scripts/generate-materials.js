import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const MATERIALS_DIR = path.join(__dirname, '..', 'public', 'materials');
const OUTPUT_FILE = path.join(__dirname, '..', 'src', 'data', 'materials.generated.ts');

const EXTENSION_TYPE_MAP = {
  '.html': 'HTML',
  '.htm': 'HTML',
  '.pdf': 'PDF',
  '.doc': 'DOCX',
  '.docx': 'DOCX',
  '.ppt': 'PPTX',
  '.pptx': 'PPTX',
  '.png': 'IMAGE',
  '.jpg': 'IMAGE',
  '.jpeg': 'IMAGE',
  '.webp': 'IMAGE',
  '.gif': 'IMAGE',
  '.svg': 'IMAGE',
};

function formatDisplayName(filename) {
  const ext = path.extname(filename);
  const base = path.basename(filename, ext);

  return base
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .split(' ')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
}

function getFileType(filename) {
  const ext = path.extname(filename).toLowerCase();
  return EXTENSION_TYPE_MAP[ext] || 'OTHER';
}

function scanFolder(folderPath, relativeUrlPrefix) {
  if (!fs.existsSync(folderPath)) return [];

  const entries = fs.readdirSync(folderPath, { withFileTypes: true });
  const items = [];

  for (const entry of entries) {
    if (entry.isFile() && !entry.name.startsWith('.')) {
      const fullPath = path.join(folderPath, entry.name);
      const stats = fs.statSync(fullPath);
      const ext = path.extname(entry.name);
      const relativeUrl = `${relativeUrlPrefix}/${encodeURIComponent(entry.name)}`;

      items.push({
        id: entry.name,
        title: formatDisplayName(entry.name),
        filename: entry.name,
        type: getFileType(entry.name),
        extension: ext.replace('.', '').toLowerCase(),
        url: relativeUrl,
        sizeInBytes: stats.size,
      });
    }
  }

  return items.sort((a, b) => a.title.localeCompare(b.title));
}

function buildMaterialsData() {
  if (!fs.existsSync(MATERIALS_DIR)) {
    fs.mkdirSync(MATERIALS_DIR, { recursive: true });
  }

  const courseDirs = fs.readdirSync(MATERIALS_DIR, { withFileTypes: true });
  const courses = [];

  for (const dir of courseDirs) {
    if (dir.isDirectory() && !dir.name.startsWith('.')) {
      const courseCode = dir.name;
      const coursePath = path.join(MATERIALS_DIR, courseCode);

      // Sub-folder discovery (case-insensitive)
      const subEntries = fs.readdirSync(coursePath, { withFileTypes: true });
      let chaptersPath = '';
      let othersPath = '';

      for (const sub of subEntries) {
        if (sub.isDirectory()) {
          if (sub.name.toLowerCase() === 'chapters') {
            chaptersPath = path.join(coursePath, sub.name);
          } else if (sub.name.toLowerCase() === 'others') {
            othersPath = path.join(coursePath, sub.name);
          }
        }
      }

      const chapters = chaptersPath
        ? scanFolder(chaptersPath, `/materials/${encodeURIComponent(courseCode)}/Chapters`)
        : [];
      const others = othersPath
        ? scanFolder(othersPath, `/materials/${encodeURIComponent(courseCode)}/Others`)
        : [];

      courses.push({
        id: courseCode.toLowerCase().replace(/\s+/g, '-'),
        code: courseCode,
        title: courseCode,
        chapters,
        others,
      });
    }
  }

  courses.sort((a, b) => a.code.localeCompare(b.code));

  const fileContent = `// THIS FILE IS AUTOMATICALLY GENERATED BY scripts/generate-materials.js
// DO NOT EDIT THIS FILE MANUALLY

export interface MaterialItem {
  id: string;
  title: string;
  filename: string;
  type: 'HTML' | 'PDF' | 'DOCX' | 'PPTX' | 'IMAGE' | 'OTHER';
  extension: string;
  url: string;
  sizeInBytes: number;
}

export interface CourseData {
  id: string;
  code: string;
  title: string;
  chapters: MaterialItem[];
  others: MaterialItem[];
}

export const generatedCourses: CourseData[] = ${JSON.stringify(courses, null, 2)};
`;

  const outputDir = path.dirname(OUTPUT_FILE);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  fs.writeFileSync(OUTPUT_FILE, fileContent, 'utf-8');
  console.log(`Generated materials manifest with ${courses.length} courses.`);
}

buildMaterialsData();